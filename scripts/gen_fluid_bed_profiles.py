"""Generate the fluid-bed seed profiles migration (docs/profiles.md).

    python3 scripts/gen_fluid_bed_profiles.py [id ...] > crates/server/migrations/0NN_name.sql

With ids, only those profiles (and no legacy renames): 021 added four that way.

The output upserts: each profile row is inserted or updated and its points
and events are replaced, so a new migration generated from this script
changes the curves in deployed databases. 014 was the first set; 015 the
current three; 021 four more with roast levels (docs/roast-guidance.md).
Applied migrations are never edited.
"""
import math, sys
T0 = 30.0          # cold beans in the chamber at CHARGE
FC = 200.0         # first crack BT on this probe (estimate)
DRY = 160.0
TAU = 200.0
PROFILES = [
    # id, name, t_fc, t_drop, T_drop, fan_late, roast level, purpose, description
    ("fluidbed-light", "Fluid bed — Light (filter)", 465, 570, 210.0, 82, "light", "filter",
     "Bright, light roast for filter. FC ~7:45 at ~200 °C, drop 9:30 at 210 °C (development ~18 %). Cold charge; declining RoR."),
    ("fluidbed-medium", "Fluid bed — Medium (filter)", 510, 660, 216.0, 80, "medium", "filter",
     "Balanced medium roast. FC ~8:30 at ~200 °C, drop 11:00 at 216 °C (development ~23 %). Cold charge; declining RoR."),
    ("fluidbed-espresso", "Fluid bed — Light espresso", 540, 690, 212.0, 80, "light", "espresso",
     "Light roast for espresso: longer, gentler development than the filter roasts so it extracts sweet rather than sour. FC ~9:00 at ~200 °C, drop 11:30 at 212 °C (development ~22 %). Cold charge; declining RoR."),
    # 021: one per gap, each inside its level's ranges (docs/roast-guidance.md).
    ("fluidbed-nordic", "Fluid bed — Extra-light filter (Nordic)", 450, 510, 205.0, 84, "extremely_light", "filter",
     "Very light, Nordic-style filter roast: drop about a minute after first crack to keep acidity and florals. FC ~7:30 at ~200 °C, drop 8:30 at 205 °C (development 1:00, ~12 %). Cold charge; declining RoR."),
    ("fluidbed-cupping", "Fluid bed — Cupping (SCA sample roast)", 480, 600, 213.0, 82, "medium_light", "other",
     "Sample roast for cupping green coffees, after the SCA protocol: 8-12 minutes to about Agtron 63 ground. FC ~8:00 at ~200 °C, drop 10:00 at 213 °C (development 2:00, ~20 %). Cold charge; declining RoR."),
    ("fluidbed-espresso-short", "Fluid bed — Light espresso, short development", 510, 615, 210.0, 80, "light", "espresso",
     "Light espresso with a development inside what a light roast expects (1:00-2:00): an alternative to the longer Light espresso when roasts come out dark. FC ~8:30 at ~200 °C, drop 10:15 at 210 °C (development 1:45, ~17 %). Cold charge; declining RoR."),
    ("fluidbed-omni", "Fluid bed — Medium-light omni", 495, 615, 213.0, 80, "medium_light", "omni",
     "Medium-light roast that works as filter and espresso. FC ~8:15 at ~200 °C, drop 10:15 at 213 °C (development 2:00, ~20 %). Cold charge; declining RoR."),
]
ONLY = set(sys.argv[1:])
def fit(t_fc, t_drop, T_drop):
    # BT(t) = T0 + c t + a τ (1 - e^{-t/τ}); solve for a, c.
    g = lambda t: TAU * (1 - math.exp(-t / TAU))
    # [t_fc g(t_fc)] [c a]^T = FC - T0 ; [t_drop g(t_drop)] = T_drop - T0
    a11, a12, b1 = t_fc, g(t_fc), FC - T0
    a21, a22, b2 = t_drop, g(t_drop), T_drop - T0
    det = a11 * a22 - a12 * a21
    c = (b1 * a22 - a12 * b2) / det
    a = (a11 * b2 - b1 * a21) / det
    bt = lambda t: T0 + c * t + a * g(t)
    ror = lambda t: (c + a * math.exp(-t / TAU)) * 60
    return bt, ror
sql = ["-- Seed profiles shaped for a cold-charged, heat-limited fluid-bed roaster",
       "-- (docs/profiles.md). Generated by a declining-RoR model:",
       "-- BT(t) = 30 + c·t + a·τ(1 − e^(−t/τ)), τ = 200 s, fitted to FC at 200 °C",
       "-- and the drop temperature. Points every 30 s; fan 100 % through drying,",
       "-- then easing to the late fan by first crack (fan assist trims below it).",
       "-- Upserts: profile rows inserted or updated, points and events replaced.",
       "-- The old generic profiles stay (sessions reference them), renamed.", ""]
for old_id, label in () if ONLY else (("default-light", "light"), ("default-medium", "medium"), ("default-dark", "dark")):
    sql.append(f"UPDATE roast_profiles SET name = 'Generic {label} (legacy, drum-style)', "
               "description = description || ' Legacy example: starts at a 95 °C charge, and its fan curve (45-75 %) is too low for the fluid bed.' "
               f"WHERE id = '{old_id}';")
sql.append("")
for pid, name, t_fc, t_drop, T_drop, fan_late, level, purpose, desc in PROFILES:
    if ONLY and pid not in ONLY:
        continue
    bt, ror = fit(t_fc, t_drop, T_drop)
    # time where BT reaches DRY
    t_dry = next(t for t in range(0, t_drop) if bt(t) >= DRY)
    print(f"{pid}: RoR start {ror(0):.0f}, dry {t_dry//60}:{t_dry%60:02d}, at FC {ror(t_fc):.1f}, at drop {ror(t_drop):.1f} C/min; BT@60 {bt(60):.0f} @240 {bt(240):.0f}", file=sys.stderr)
    assert ror(t_drop) > 2 and all(ror(t) > ror(t + 1) for t in range(t_drop)), "RoR must decline and stay positive"
    sql.append(f"INSERT INTO roast_profiles (id, name, description, is_public, target_total_time, target_first_crack, target_end_temp, charge_temp, roast_level, roast_purpose) VALUES "
               f"('{pid}', '{name}', '{desc}', 1, {t_drop}, {t_fc}, {T_drop}, {T0}, '{level}', '{purpose}') "
               "ON CONFLICT(id) DO UPDATE SET name = excluded.name, description = excluded.description, "
               "target_total_time = excluded.target_total_time, target_first_crack = excluded.target_first_crack, "
               "target_end_temp = excluded.target_end_temp, charge_temp = excluded.charge_temp, "
               "roast_level = excluded.roast_level, roast_purpose = excluded.roast_purpose;")
    sql.append(f"DELETE FROM profile_points WHERE profile_id = '{pid}';")
    sql.append(f"DELETE FROM profile_events WHERE profile_id = '{pid}';")
    times = list(range(0, t_drop, 30)) + [t_drop]
    rows = []
    for i, t in enumerate(times):
        if t <= 240: fan = 100
        elif t >= t_fc: fan = fan_late
        else: fan = round(100 - (100 - fan_late) * (t - 240) / (t_fc - 240))
        rows.append(f"('{pid}-p{i:02d}', '{pid}', {t}, {bt(t):.1f}, {fan})")
    sql.append("INSERT INTO profile_points (id, profile_id, time_seconds, target_temp, fan_speed) VALUES\n" + ",\n".join(rows) + ";")
    sql.append("INSERT INTO profile_events (id, profile_id, trigger_kind, at_seconds, at_bt, action, value, label) VALUES\n"
               f"('{pid}-dry', '{pid}', 'bt', {t_dry}, {DRY}, 'landmark', NULL, 'drying_end'),\n"
               f"('{pid}-fc', '{pid}', 'bt', {t_fc}, {FC}, 'landmark', NULL, 'first_crack_start');")
    sql.append("")
print("\n".join(sql))
